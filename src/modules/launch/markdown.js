import { humanize } from "@/lib/humanize";
import { BUDGET_LABELS } from "./schemas.js";
import { LAUNCH_SECTIONS } from "./sections.js";

/** Escapes characters that would change Markdown structure in user/AI text. */
function esc(text) {
  return String(text ?? "").replace(/([\\`*_{}[\]<>#|])/g, "\\$1");
}

function renderValue(value, depth) {
  if (value == null || value === "") return "";
  if (typeof value !== "object") return esc(value);
  if (Array.isArray(value)) {
    if (value.every((v) => typeof v !== "object")) return value.map((v) => `- ${esc(v)}`).join("\n");
    return value.map((item) => renderObject(item, depth + 1, true)).join("\n\n");
  }
  return renderObject(value, depth + 1, false);
}

function renderObject(obj, depth, asItem) {
  const entries = Object.entries(obj).filter(([, v]) => v != null && v !== "" && !(Array.isArray(v) && v.length === 0));
  const titleKey = asItem ? ["name", "title", "task", "problem", "milestone", "item", "risk"].find((k) => typeof obj[k] === "string") : null;
  const lines = [];
  if (titleKey) lines.push(`${"#".repeat(Math.min(6, depth + 2))} ${esc(obj[titleKey])}`);
  for (const [key, value] of entries) {
    if (key === titleKey) continue;
    if (typeof value === "object") lines.push(`**${humanize(key)}**\n\n${renderValue(value, depth)}`);
    else lines.push(`**${humanize(key)}:** ${esc(value)}`);
  }
  return lines.join("\n\n");
}

/** Renders a launch pack (pure) — used by the export endpoint. */
export function renderLaunchPackMarkdown({ project, business, outputs }) {
  const input = project.input;
  const parts = [
    `# ${esc(business.name)} — Launch Pack`,
    `_Generated with Brand AI Business Launch Studio. AI-generated content: review before relying on it._`,
    `## Business idea`,
    esc(input.idea),
    `**Location:** ${esc([input.city, input.country].filter(Boolean).join(", "))}  \n**Stage:** ${esc(input.stage)}  \n**Budget:** ${esc(BUDGET_LABELS[input.budget] ?? input.budget)}`,
  ];
  for (const section of LAUNCH_SECTIONS) {
    const output = outputs[section.key];
    if (!output) continue;
    parts.push(`## ${section.title}`);
    if (output.isMock) parts.push("> Test data generated by the mock AI provider.");
    parts.push(renderValue(output.content, 0));
  }
  return parts.join("\n\n") + "\n";
}
