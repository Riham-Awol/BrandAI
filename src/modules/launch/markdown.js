import { mdEscape as esc, renderStructured as renderValue } from "@/lib/markdown";
import { BUDGET_LABELS } from "./schemas.js";
import { LAUNCH_SECTIONS } from "./sections.js";

/** Renders a launch pack (pure) — used by the export endpoint. */
export function renderLaunchPackMarkdown({ project, business, outputs }) {
  const input = project.input;
  const parts = [
    `# ${esc(business.name)} — Launch Pack`,
    `_Generated with Brand AI Business Launch Studio. AI-generated content: review before relying on it._`,
    `## Business idea`,
    esc(input.idea),
    `**Location:** ${esc([input.city, input.country].filter(Boolean).join(", "))}  \n**Stage:** ${esc(input.stage)}  \n**Budget:** ${esc(BUDGET_LABELS[input.budget] ?? input.budget)}`,
  ];
  for (const section of LAUNCH_SECTIONS) {
    const output = outputs[section.key];
    if (!output) continue;
    parts.push(`## ${section.title}`);
    if (output.isMock) parts.push("> Test data generated by the mock AI provider.");
    parts.push(renderValue(output.content, 0));
  }
  return parts.join("\n\n") + "\n";
}
